public class Operators {
    public static void main(String[] args) {
        int a = 17;
        int b = 5;
        System.out.println(a / b);
        System.out.println(a % b);
        System.out.println(a + b * 2);
        System.out.println(17 / 5.0);
        System.out.println("Sum: " + 4 + 6);
        System.out.println(4 + 6 + " is sum");
        System.out.println("Sum: " + (4 + 6));
    }
}