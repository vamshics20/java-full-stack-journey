public class ComparisonOperators {
    public static void main(String[] args) {
        String className = "VAMSHI LANKALA";
        int marks = 50;
        System.out.println("VAMSHI LANKALA" .equals(className));
        System.out.println((50) != marks);
        System.out.println((63) > marks);
        System.out.println((65) < marks);
        System.out.println((67) >= marks);
        System.out.println((65) <= marks);

    }

}
