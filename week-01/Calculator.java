public class Calculator {
    public static void main(String[] args) {
        int a = 20;
        int b = 13;
        System.out.println("a + b =" + (a + b));
        System.out.println("a - b =" + (a - b));
        System.out.println("a * b =" + (a * b));
        System.out.println("a / b =" + (a / b));
        System.out.println("a % b =" + (a % b));
        double c = 16.9;
        System.out.println("c - a =" + (c - a));
        System.out.println("c % a =" + (c % a));
        System.out.println("c / b =" + (c / b));

    }
}